import LanguageConfiguration = monaco.languages.LanguageConfiguration;
import IMonarchLanguage = monaco.languages.IMonarchLanguage;

// Язык «1С:Элемент» (в инструментах известен как xBSL; скрипты — файлы .sbsl).
// Среда выполнения — «Элемент Скрипт», статическая типизация, ключевые слова
// пишутся строчными буквами, стандартная библиотека — в пространствах имён
// вида Стд::Строка.
//
// Грамматика намеренно лёгкая: подсветка и конфигурация языка, без диагностики
// и автодополнения — они подключаются отдельно, если понадобятся.
export const XBSL_LANGUAGE_ID = "xbsl";

export const conf: LanguageConfiguration = {
  comments: {
    lineComment: "//",
    blockComment: ["/*", "*/"],
  },
  brackets: [
    ["{", "}"],
    ["[", "]"],
    ["(", ")"],
  ],
  autoClosingPairs: [
    { open: "\"", close: "\"", notIn: ["string"] },
    { open: "{", close: "}" },
    { open: "[", close: "]" },
    { open: "(", close: ")" },
  ],
  surroundingPairs: [
    { open: "\"", close: "\"" },
    { open: "{", close: "}" },
    { open: "[", close: "]" },
    { open: "(", close: ")" },
  ]
};

// Список ключевых слов — по документации ИТС: «Список инструкций, операций и
// символов» (its-pub1celementarno-307) и «Ключевые слова» (its-pubelementlang-10).
//
// ignoreCase выключен осознанно: в языке ключевые слова только строчные, и
// «Если» — это не ключевое слово, а неизвестная переменная. Подсветка должна
// показывать это так же, как компилятор.
export const language: IMonarchLanguage = <IMonarchLanguage>{
  defaultToken: '',
  ignoreCase: false,

  keywords: [
    // Блоки кода.
    'метод', 'область',
    // Инструкции.
    'выбор', 'выбросить', 'для', 'из', 'по', 'если', 'иначе', 'исключение',
    'когда', 'знч', 'исп', 'конст', 'пер', 'перечисление', 'пока', 'попытка',
    'структура', 'возврат', 'прервать', 'продолжить', 'вниз',
    // Операции и прочие ключевые слова.
    'и', 'или', 'не', 'новый', 'как', 'это', 'конструктор', 'обз',
    'статический', 'неизвестно', 'ничто', 'умолчание', 'этот',
    // Литерал типа «Неопределено» пишется с прописной буквы.
    'Неопределено',
  ],

  brackets: [
    { open: '{', close: '}', token: 'delimiter.curly' },
    { open: '[', close: ']', token: 'delimiter.square' },
    { open: '(', close: ')', token: 'delimiter.parenthesis' },
  ],

  operators: [
    '=', '==', '!=', '<', '<=', '>', '>=', '+', '-', '*', '/', '%',
    '**', '+=', '-=', '*=', '/=', '->', '??', '|',
    // «?» — тернарная операция и безопасный доступ, «!» — настойчивая операция.
    '?', '!',
  ],
  symbols: /[=!<>+\-*\/%?|]+/,

  tokenizer: {
    root: [
      // Директива импорта: #требуется (знак номера — начало директивы).
      [/#[А-Яа-яЁёA-Za-z_]+/, 'keyword'],
      // Аннотация: @Глобально, @Локально, @Наименование. Отдельный токен, а не
      // keyword: в 1С:Элемент аннотации выделяются своим цветом, и тема должна
      // иметь возможность задать его независимо от ключевых слов.
      [/@[А-Яа-яЁёA-Za-z_]+/, 'annotation'],
      // Ссылка на метод: &ИмяМетода.
      [/&[А-Яа-яЁёA-Za-z_]+/, 'identifier'],
      // Пространство имён стандартной библиотеки: Стд::Строка.
      [/[А-Яа-яЁёA-Za-z_][А-Яа-яЁёA-Za-z_0-9]*::/, 'type'],
      // Объявление метода: имя после «метод»/«конструктор» — не переменная,
      // поэтому оно уходит в отдельный токен (function).
      [/метод(?![А-Яа-яЁёA-Za-z_0-9])/, { token: 'keyword', next: '@methodName' }],
      [/конструктор(?![А-Яа-яЁёA-Za-z_0-9])/, { token: 'keyword', next: '@methodName' }],
      // Объявление переменной: имя после «знч»/«пер»/«конст».
      [/знч(?![А-Яа-яЁёA-Za-z_0-9])/, { token: 'keyword', next: '@variableName' }],
      [/пер(?![А-Яа-яЁёA-Za-z_0-9])/, { token: 'keyword', next: '@variableName' }],
      [/конст(?![А-Яа-яЁёA-Za-z_0-9])/, { token: 'keyword', next: '@variableName' }],
      [/[А-Яа-яЁёA-Za-z_][А-Яа-яЁёA-Za-z_0-9]*/, {
        cases: {
          '@keywords': 'keyword',
          '@default': 'identifier',
        }
      }],
      { include: '@whitespace' },
      // Строковый литерал. В языке строки бывают многострочными — перенос
      // внутри кавычек значим, — поэтому разбор идёт через состояние.
      [/"/, 'string', '@string'],
      // Регулярное выражение в апострофах.
      [/'(?:[^'\\]|\\.)*'/, 'regexp'],
      [/'/, 'delimiter'],
      // Числа.
      [/[0-9]+\.[0-9]+([eE][\-+]?\d+)?/, 'number.float'],
      [/[0-9]+/, 'number'],
      [/[;:,.]/, 'delimiter'],
      [/[{}()\[\]]/, '@brackets'],
      [/@symbols/, {
        cases: {
          '@operators': 'operator',
          '@default': 'delimiter'
        }
      }],
    ],

    // Тело строки. Конец — неэкранированная кавычка; всё остальное, включая
    // переводы строк, остаётся строкой.
    string: [
      [/[^"\\$%]+/, 'string'],
      [/\\./, 'string.escape'],
      // Выражение интерполяции: ${выражение} и %{выражение}.
      [/\$\{/, 'string', '@interpolation'],
      [/%\{/, 'string', '@interpolation'],
      // Короткая форма: $Имя и %Имя.
      [/[$%][А-Яа-яЁёA-Za-z_][А-Яа-яЁёA-Za-z_0-9]*/, 'string.interpolation'],
      [/[$%]/, 'string'],
      [/"/, 'string', '@pop'],
    ],

    // Выражение внутри интерполяции подсвечивается как код.
    interpolation: [
      [/\}/, 'string', '@pop'],
      { include: '@root' },
    ],

    // Имя объявляемого метода: первый идентификатор после «метод».
    methodName: [
      [/[\r\n]/, { token: '', next: '@pop' }],
      { include: '@whitespace' },
      [/[А-Яа-яЁёA-Za-z_][А-Яа-яЁёA-Za-z_0-9]*/, { token: 'function', next: '@signature' }],
      [/./, { token: '', next: '@pop' }],
    ],

    // Список параметров объявления. Держим его одним состоянием без вложенности:
    // вложенные pop-ы легко «застрять» на пустом списке и съесть следующий символ.
    // Имя параметра — переменная, тип после «:» уходит в @typeName.
    signature: [
      [/[\r\n]/, { token: '', next: '@pop' }],
      { include: '@whitespace' },
      [/:/, { token: 'delimiter', next: '@typeName' }],
      [/[(),]/, 'delimiter.parenthesis'],
      [/[А-Яа-яЁёA-Za-z_][А-Яа-яЁёA-Za-z_0-9]*/, 'variable'],
      { include: '@root' },
    ],

    // Имя типа: ВыборФайлов, ДвоичныйОбъект.Ссылка, ЧитаемыйМассив<ВыбранныйФайл>.
    typeName: [
      [/[\r\n]/, { token: '', next: '@pop' }],
      [/,/, { token: 'delimiter', next: '@pop' }],
      [/\)/, { token: 'delimiter.parenthesis', next: '@pop' }],
      { include: '@whitespace' },
      [/[А-Яа-яЁёA-Za-z_][А-Яа-яЁёA-Za-z_0-9]*::/, 'type'],
      [/[А-Яа-яЁёA-Za-z_][А-Яа-яЁёA-Za-z_0-9]*/, 'type'],
      [/[<>?.\[\]]/, 'type'],
    ],

    // Имя объявляемой переменной: первый идентификатор после «знч»/«пер»/«конст».
    variableName: [
      [/[\r\n]/, { token: '', next: '@pop' }],
      { include: '@whitespace' },
      [/[А-Яа-яЁёA-Za-z_][А-Яа-яЁёA-Za-z_0-9]*/, { token: 'variable', next: '@pop' }],
      [/./, { token: '', next: '@pop' }],
    ],

    whitespace: [
      [/[ \t\r\n]+/, ''],
      [/\/\/.*$/, 'comment'],
      [/\/\*/, 'comment', '@blockComment'],
    ],

    blockComment: [
      [/[^*\/]+/, 'comment'],
      [/\*\//, 'comment', '@pop'],
      [/[*\/]/, 'comment'],
    ],
  },
};
